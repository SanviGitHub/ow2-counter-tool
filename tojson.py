# Build counterinfo.csv
with open("counterinfo.csv", "w", encoding="utf-8", newline="") as f:
    writer = csv.DictWriter(f, fieldnames=["Hero Name", "Role", "Portrait Img", "Icon Img", "Counters", "Weaknesses"])
    writer.writeheader()
    for row in hero_data_out:
        writer.writerow({
            "Hero Name": row["Hero Name"],
            "Role": row["Role"],
            "Portrait Img": row["Portrait Img"],
            "Icon Img": row["Icon Img"],
            "Counters": row["Counters"],
            "Weaknesses": row["Weaknesses"]
        })

