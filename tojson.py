# Build heroscript.json (enriched & backwards-compatible)
heroscript_out = []
for h in heroes:
    counter_imgs = [name_to_hero[c]["portrait_img"] for c in h["counters"] if c in name_to_hero]
    weakness_imgs = [name_to_hero[w]["portrait_img"] for w in h["weaknesses"] if w in name_to_hero]
    heroscript_out.append({
        "key": h["key"],
        "name": h["name"],
        "role": f"{h['playstyle']} {h['role']}",
        "base_role": h["role"],
        "subrole": h["subrole"],
        "playstyle": h["playstyle"],
        "tier": h["tier"],
        "difficulty": h["difficulty"],
        "portrait_img": h["portrait_img"],
        "grid_img": h["grid_img"],
        "counters": counter_imgs,
        "counter_names": h["counters"],
        "weaknesses": weakness_imgs,
        "weakness_names": h["weaknesses"],
        "synergies": h["synergies"],
        "tip": h["tip"]
    })

with open("heroscript.json", "w", encoding="utf-8") as f:
    json.dump(heroscript_out, f, indent=2, ensure_ascii=False)

# Build hero_data.json
hero_data_out = []
